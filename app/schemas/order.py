from typing import Optional, List
from datetime import date, datetime
from pydantic import BaseModel, Field
from app.models.order import OrderPriority, OrderStatus
from app.schemas.route import OrderRouteCreate, OrderRouteOut


class DeliveryRevisionCreate(BaseModel):
    revised_delivery_date: date
    reason: str = Field(..., min_length=2)


class DeliveryRevisionOut(BaseModel):
    id: int
    order_id: int
    previous_delivery_date: date
    revised_delivery_date: date
    reason: str
    revised_by_id: int
    revised_by_name: Optional[str] = None
    created_at: datetime

    class Config:
        from_attributes = True


class OrderCreate(BaseModel):
    buyer_id: int
    order_code: Optional[str] = None  # Autogenerated if None e.g. ORD-2026-0001
    customer_ref: str
    po_number: Optional[str] = None
    style_model: str
    description: Optional[str] = None
    total_quantity: float = Field(..., gt=0, description="Total order pairs")
    original_order_date: Optional[date] = None
    production_start_date: Optional[date] = None
    original_delivery_date: date
    priority: OrderPriority = OrderPriority.MEDIUM
    notes: Optional[str] = None
    # Configurable production routes
    routes: List[OrderRouteCreate] = []


class OrderUpdate(BaseModel):
    customer_ref: Optional[str] = None
    po_number: Optional[str] = None
    style_model: Optional[str] = None
    description: Optional[str] = None
    total_quantity: Optional[float] = None
    production_start_date: Optional[date] = None
    current_delivery_date: Optional[date] = None
    priority: Optional[OrderPriority] = None
    status: Optional[OrderStatus] = None
    notes: Optional[str] = None
    reason: Optional[str] = None  # For audit trail when quantity or delivery date changes
    routes: Optional[List[OrderRouteCreate]] = None
    confirm_workflow_change: bool = False


class OrderOut(BaseModel):
    id: int
    order_code: str
    buyer_id: int
    buyer_name: Optional[str] = None
    customer_ref: str
    po_number: Optional[str] = None
    style_model: str
    description: Optional[str] = None
    total_quantity: float
    original_order_date: date
    production_start_date: date
    original_delivery_date: date
    current_delivery_date: date
    priority: OrderPriority
    status: OrderStatus
    notes: Optional[str] = None
    created_at: datetime
    updated_at: datetime
    
    # Computed metrics
    remaining_working_days: int = 0
    remaining_days: int = 0
    completed_pairs: float = 0.0
    outstanding_pairs: float = 0.0
    completion_percentage: float = 0.0
    daily_target: float = 0.0
    today_actual: float = 0.0
    today_variance: float = 0.0
    overdue_balance: float = 0.0
    running_date: Optional[date] = None
    shipment_date: Optional[date] = None
    order_quantity: Optional[float] = None
    produced_quantity: Optional[float] = None
    balance_quantity: Optional[float] = None
    forecast_completion_date: Optional[date] = None
    is_archived: bool = False
    is_at_risk: bool = False
    is_overdue: bool = False

    class Config:
        from_attributes = True


class OrderDetailOut(OrderOut):
    routes: List[OrderRouteOut] = []
    delivery_revisions: List[DeliveryRevisionOut] = []


class OrderDependencyCheckOut(BaseModel):
    order_id: int
    order_code: str
    customer_ref: str
    buyer_name: str
    total_quantity: float
    production_entries_count: int
    has_production_history: bool
    can_permanently_delete: bool
    can_archive: bool
    message: str


class OrderArchiveRequest(BaseModel):
    reason: Optional[str] = "Archived by user"
